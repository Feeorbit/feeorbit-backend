const mongoose = require('mongoose');

const chatBlockSchema = new mongoose.Schema(
  {
    gym: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Gym',
      required: true,
      index: true,
    },
    blocker: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
      index: true,
    },
    blocked: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
      index: true,
    },
    reason: {
      type: String,
      default: '',
      trim: true,
    },
    createdAt: {
      type: Date,
      default: Date.now,
    },
  },
  { timestamps: true }
);

chatBlockSchema.index({ blocker: 1, blocked: 1 }, { unique: true });
chatBlockSchema.index({ gym: 1, blocker: 1 });

module.exports = mongoose.model('ChatBlock', chatBlockSchema);
